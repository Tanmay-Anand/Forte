/**
 * Builds the body figures for the phone and the companion from the MuscleMap
 * diagrams in vendor/musclemap. Run it again only when those files, the
 * muscle mapping (src/features/analysis/body-regions.ts) or the teal in
 * src/ui/tokens.ts change; its output is committed.
 *
 *   node tools/bake-body.mjs              outlines and images
 *   node tools/bake-body.mjs --no-images  outlines only
 *
 * Outlines (no browser needed):
 *   src/data/body/male.ts, female.ts   muscle outlines for the phone
 *   companion/web/body-data.js         the same, for the companion
 *
 * Images: Node can't draw, so this serves a page on 127.0.0.1:4190 that
 * draws them with the browser's canvas and sends them back. Open it once.
 *   assets/body/<sex>-<view>-base.webp        the photo, grey, cut to the body
 *   assets/body/<sex>-<view>-glow-dark.webp   the same with the dark theme's teal blended in
 *   assets/body/<sex>-<view>-glow-light.webp  ... and the light theme's
 *
 * The phone draws the grey photo, then the teal one clipped to each trained
 * muscle at that muscle's opacity. All the blending happens here, once, so
 * the phone only ever does plain transparency.
 */
import http from 'node:http';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { bodyMuscle } from '../src/features/analysis/body-regions.ts';
import { palette } from '../src/ui/tokens.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(ROOT, 'vendor/musclemap');
const PORT = 4190;

/** The part of the 1024 × 1536 photo the figures show: the body, without the empty margins. */
const CROP = { x: 150, y: 20, w: 724, h: 1496 };
/** Image size relative to the photo: 434 × 898, sharp at the size a phone shows it. */
const SCALE = 0.6;
/** The companion's grey (companion/web/app.css before this script existed). */
const GREY = 'grayscale(1) contrast(1.15) brightness(.62)';

const SEXES = ['male', 'female'];
const VIEWS = ['front', 'back'];

const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n))));

async function diagram(sex, view) {
  const mod = await import(pathToFileURL(path.join(SOURCE, `${sex}-${view}.js`)).href);
  return Object.values(mod)[0];
}

/** One view's muscles, the MuscleMap regions of each merged into one outline. */
function muscles(d, view) {
  const by = new Map();
  for (const m of d.muscles) {
    const muscle = bodyMuscle(m.group, view);
    if (!muscle) continue;
    by.set(muscle, [...(by.get(muscle) ?? []), round(m.d)]);
  }
  return [...by.entries()].map(([muscle, parts]) => ({ muscle, d: parts.join(' ') }));
}

async function outlines() {
  const data = {};
  for (const sex of SEXES) {
    data[sex] = {};
    for (const view of VIEWS) data[sex][view] = muscles(await diagram(sex, view), view);
  }

  const header = (what) =>
    `// Generated by tools/bake-body.mjs from vendor/musclemap (MuscleMap, MIT). Do not edit.\n// ${what}\n`;
  await mkdir(path.join(ROOT, 'src/data/body'), { recursive: true });
  for (const sex of SEXES) {
    const name = sex.toUpperCase();
    await writeFile(
      path.join(ROOT, `src/data/body/${sex}.ts`),
      `${header(`Muscle outlines of the ${sex} body, in the photo's 1024 × 1536 space.`)}` +
        `import type { BodyOutlines } from './types';\n\n` +
        `export const ${name}: BodyOutlines = ${JSON.stringify(data[sex], null, 1)};\n`,
    );
  }
  await writeFile(
    path.join(ROOT, 'src/data/body/types.ts'),
    `${header('Shapes of the generated body data.')}` +
      `import type { Muscle } from '@/features/analysis';\n\n` +
      `export type BodyOutlines = Record<'front' | 'back', { muscle: Muscle; d: string }[]>;\n\n` +
      `/** The part of the photo the images show (x, y, width, height). */\n` +
      `export const BODY_CROP = ${JSON.stringify(CROP)} as const;\n`,
  );
  await writeFile(
    path.join(ROOT, 'companion/web/body-data.js'),
    `${header("Muscle outlines for the companion's Body page.")}` +
      `export const CROP = ${JSON.stringify(CROP)};\n\nexport const BODY = ${JSON.stringify(data)};\n`,
  );
  console.log('Wrote src/data/body/{male,female,types}.ts and companion/web/body-data.js');
}

// ------------------------------------------------------------------ images

const PAGE = `<!doctype html><meta charset="utf-8"><title>Baking body images</title>
<body style="font:15px system-ui;background:#111;color:#eee;padding:24px"><p id="s">Baking…</p>
<script type="module">
const job = await fetch('/job').then((r) => r.json());
const s = document.getElementById('s');
const W = Math.round(job.crop.w * job.scale), H = Math.round(job.crop.h * job.scale);

function canvas() {
  const c = document.createElement('canvas');
  c.width = W; c.height = H;
  const ctx = c.getContext('2d');
  ctx.setTransform(job.scale, 0, 0, job.scale, -job.crop.x * job.scale, -job.crop.y * job.scale);
  return [c, ctx];
}
function cut(ctx, outline) {
  ctx.globalCompositeOperation = 'destination-in';
  ctx.fill(outline);
  ctx.globalCompositeOperation = 'source-over';
}
async function save(name, c) {
  const blob = await new Promise((r) => c.toBlob(r, 'image/webp', 0.85));
  await fetch('/save?name=' + name, { method: 'POST', body: blob });
}

for (const { sex, view, outline } of job.bodies) {
  const img = new Image();
  img.src = '/source/' + sex + '-' + view + '.webp';
  await img.decode();
  const shape = new Path2D(outline);

  const [base, b] = canvas();
  b.filter = job.grey;
  b.drawImage(img, 0, 0, 1024, 1536);
  b.filter = 'none';
  cut(b, shape);
  await save(sex + '-' + view + '-base', base);

  for (const [theme, teal] of Object.entries(job.teal)) {
    const [glow, g] = canvas();
    g.save(); g.setTransform(1, 0, 0, 1, 0, 0); g.drawImage(base, 0, 0); g.restore();
    g.globalCompositeOperation = 'hard-light';
    g.fillStyle = teal;
    g.fillRect(0, 0, 1024, 1536);
    g.globalCompositeOperation = 'source-over';
    cut(g, shape);
    await save(sex + '-' + view + '-glow-' + theme, glow);
  }
  s.textContent = 'Baked ' + sex + ' ' + view;
}
await fetch('/done', { method: 'POST' });
s.textContent = 'Done. You can close this tab.';
</script>`;

async function images() {
  const bodies = [];
  for (const sex of SEXES)
    for (const view of VIEWS) {
      const d = await diagram(sex, view);
      bodies.push({ sex, view, outline: d.outline.map((o) => o.d).join(' ') });
    }
  const job = { crop: CROP, scale: SCALE, grey: GREY, teal: { dark: palette.dark.now, light: palette.light.now }, bodies };
  const out = path.join(ROOT, 'assets/body');
  await mkdir(out, { recursive: true });

  const server = http.createServer(async (req, res) => {
    const url = new URL(req.url, `http://127.0.0.1:${PORT}`);
    const send = (status, type, body) => res.writeHead(status, { 'Content-Type': type }).end(body);
    if (req.method === 'GET' && url.pathname === '/') return send(200, 'text/html; charset=utf-8', PAGE);
    if (req.method === 'GET' && url.pathname === '/job') return send(200, 'application/json', JSON.stringify(job));
    const source = url.pathname.match(/^\/source\/((?:male|female)-(?:front|back))\.webp$/);
    if (req.method === 'GET' && source) return send(200, 'image/webp', await readFile(path.join(SOURCE, `${source[1]}.webp`)));
    if (req.method === 'POST' && url.pathname === '/save') {
      const name = url.searchParams.get('name') ?? '';
      if (!/^(male|female)-(front|back)-(base|glow-dark|glow-light)$/.test(name)) return send(400, 'text/plain', 'Bad name');
      const chunks = [];
      for await (const c of req) chunks.push(c);
      await writeFile(path.join(out, `${name}.webp`), Buffer.concat(chunks));
      console.log(`  assets/body/${name}.webp`);
      return send(200, 'text/plain', 'ok');
    }
    if (req.method === 'POST' && url.pathname === '/done') {
      send(200, 'text/plain', 'ok');
      console.log('Images done.');
      server.close();
      return;
    }
    send(404, 'text/plain', 'Not found');
  });
  server.listen(PORT, '127.0.0.1', () => console.log(`Open http://127.0.0.1:${PORT} in a browser to bake the images.`));
}

await outlines();
if (!process.argv.includes('--no-images')) await images();
